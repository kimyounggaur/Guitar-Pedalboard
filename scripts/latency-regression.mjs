import assert from 'node:assert/strict';
import console from 'node:console';
import { Buffer } from 'node:buffer';
import { build } from 'esbuild';
import { fileURLToPath, URL } from 'node:url';
const bundle = await build({ entryPoints: [fileURLToPath(new URL('../src/audio/AudioEngine.ts', import.meta.url))], bundle: true, format: 'esm', platform: 'node', target: 'node20', write: false });
const { AudioEngine } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
const engine = AudioEngine.getInstance();
assert.deepEqual(engine.readLatency(), { base: null, output: null, input: null, sampleRate: 0 });
assert.equal(engine.readAudioGlitchCount(), null);
engine.context = { state: 'running', sampleRate: 48000, baseLatency: 0.01, outputLatency: 0.005, playbackStats: { underrunEvents: 3 } };
engine.stream = { getAudioTracks: () => [{ getSettings: () => ({ latency: 0.002 }) }] };
assert.deepEqual(engine.readLatency(), { base: 10, output: 5, input: 2, sampleRate: 48000 });
assert.equal(engine.readAudioGlitchCount(), 3);
engine.context.playbackStats.underrunEvents = 0;
assert.equal(engine.readAudioGlitchCount(), 0);
engine.context.playbackStats.underrunEvents = NaN;
assert.equal(engine.readAudioGlitchCount(), null);
delete engine.context.playbackStats;
delete engine.context.outputLatency;
engine.stream = { getAudioTracks: () => [{ getSettings: () => ({}) }] };
assert.deepEqual(engine.readLatency(), { base: 10, output: null, input: null, sampleRate: 48000 });
assert.equal(engine.readAudioGlitchCount(), null);
engine.stream = { getAudioTracks: () => { throw new Error('device lost'); } };
assert.equal(engine.readLatency().input, null);
console.log('Latency regression passed: device settings, unsupported data and playback underrun statistics.');
